export function resolveLanguage(preference, languages = []) {
  if (preference === "en" || preference === "zh") return preference;
  return languages
    .find((language) => /^(zh|en)(-|$)/i.test(language))
    ?.toLowerCase()
    .startsWith("zh")
    ? "zh"
    : "en";
}
